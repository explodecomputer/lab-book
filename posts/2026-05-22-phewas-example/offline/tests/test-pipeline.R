testthat::test_that("fresh local runner exports complete inventories and shared scientific outputs offline", {
  disable_remote_access()
  testthat::expect_error(ieugwasr::tophits("ieu-a-7"), "Remote access disabled")
  testthat::expect_error(utils::download.file("https://example.com", tempfile()), "Remote access disabled")
  inputs <- reconstruct_chd_inputs(testthat::test_path("../.."))
  output_dir <- tempfile("chd-integration-")
  on.exit(unlink(output_dir, recursive = TRUE), add = TRUE)
  result <- run_offline_analysis(inputs, output_dir = output_dir,
    module_dir = testthat::test_path("../R"))
  testthat::expect_equal(nrow(result$tables$lead_inventory), 41L)
  testthat::expect_equal(nrow(result$comparisons), 23L)
  testthat::expect_equal(nrow(result$decomposition), 23L)
  testthat::expect_equal(length(unique(result$comparisons$target_snp)), 18L)
  testthat::expect_equal(nrow(result$pooled), 5L)
  testthat::expect_equal(sum(result$comparisons$status == "available"), 22L)
  unavailable <- subset(result$comparisons, status != "available")
  testthat::expect_equal(unavailable$pair_id, "ieu-b-5138::rs10139550")
  testthat::expect_true(all(result$pooled$n_exclusion_loci == 41L))
  testthat::expect_true(all(grepl("rs17678683", result$pooled$excluded_locus_snps)))
  testthat::expect_false("rs17678683" %in% inputs$outgwasf$SNP)
  counts <- inputs$extraction_counts
  testthat::expect_equal(counts$queried[counts$source == "outcome_leads_found"], 41L)
  testthat::expect_equal(counts$found[counts$source == "outcome_leads_found"], 40L)
  testthat::expect_equal(counts$queried[counts$source == "outcome_instruments_found"], 992L)
  testthat::expect_equal(counts$found[counts$source == "outcome_instruments_found"], 984L)
  index <- match(result$comparisons$mediator_id, result$pooled$mediator_id)
  testthat::expect_identical(result$comparisons$comparator_b, result$pooled$b[index])
  testthat::expect_identical(result$comparisons$comparator_se, result$pooled$se[index])
  testthat::expect_identical(result$comparisons$usable_SNPs, result$pooled$usable_SNPs[index])
  testthat::expect_true(all(result$decomposition$total_status == "complete"))
  testthat::expect_equal(length(result$plots$comparisons), 5L)
  testthat::expect_equal(length(result$plots$decomposition), 4L)
  testthat::expect_equal(length(result$plots$pooled), 1L)
  testthat::expect_true(all(file.exists(unlist(result$plots))))
  testthat::expect_true(all(result$tables$covariance_sensitivity$covariance_psd))
  testthat::expect_equal(length(unique(result$tables$covariance_sensitivity$i_family)), 3L)
  testthat::expect_equal(nrow(result$summary$families), 12L)
  for (name in names(result$tables))
    testthat::expect_equal(nrow(read.csv(file.path(output_dir, paste0(name, ".csv")))), nrow(result$tables[[name]]))
})
